-- ============================================================
-- Боксы как отдельные календари. Схему БД НЕ меняем:
-- один бокс = одна строка в public.businesses (у каждой свой календарь и своё ограничение на пересечения броней).
-- Выполните в Supabase → SQL Editor. UUID должны совпадать с boxes[].businessId в src/business.json.
--
-- Бокс №1 использует основную строку (businessId из business.json), для неё ничего не нужно.
-- Боксы №2 и №3 создаются копированием владельца/телефона из основной строки.
-- ВАЖНО: если у всех боксов в business.json один и тот же businessId, они делят ОДИН календарь:
-- пока занят один бокс, остальные не получится забронировать на то же время.
-- ============================================================

insert into public.businesses (id, owner_id, name, phone, description)
select v.id, b.owner_id, v.name, b.phone, b.description
from public.businesses b,
     (values
       ('88888888-8888-8888-8888-888888888802'::uuid, 'Бокс №2 — Оклейка плёнкой'),
       ('88888888-8888-8888-8888-888888888803'::uuid, 'Бокс №3 — Мойка и салон')
     ) as v(id, name)
where b.id = '2ead704b-12f6-4857-b0ce-ba8a64433291'
on conflict (id) do nothing;
